// Bundles src/main.ts into dist/Code.js for the Apps Script V8 runtime.
//
// Apps Script has no module system: it loads every file into one global scope and finds
// entrypoints (doGet, doPost, onOpen, menu and trigger handlers) by looking for top-level
// function declarations. esbuild wraps the bundle in an IIFE assigned to one global, so this
// script appends a top-level function for each export of src/main.ts that calls into it.
//
// Usage: node scripts/build.js   (pnpm dev re-runs it on changes via node --watch-path)
import { copyFile, mkdir, rm } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as esbuild from 'esbuild';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const ENTRY = 'src/main.ts';
const MANIFEST = 'appsscript.json';
const GLOBAL_NAME = 'ScriptKit';

/** @type {import('esbuild').BuildOptions} */
const COMMON = {
  absWorkingDir: ROOT,
  entryPoints: [ENTRY],
  bundle: true,
  // 'neutral' gives no Node.js built-ins, which Apps Script does not have either.
  platform: 'neutral',
  target: 'es2019',
  logLevel: 'warning',
};

/**
 * The names exported by src/main.ts, sorted so the output is reproducible.
 * @returns {Promise<string[]>}
 */
async function entrypointNames() {
  const result = await esbuild.build({
    ...COMMON,
    format: 'esm',
    outfile: 'entrypoints.js',
    write: false,
    metafile: true,
  });
  const names = Object.values(result.metafile.outputs).flatMap((output) => output.exports);
  if (names.includes('default')) {
    throw new Error(`${ENTRY} must use named exports: Apps Script calls entrypoints by name.`);
  }
  return names.sort();
}

/**
 * Writes Code.js and appsscript.json to outdir (absolute, or relative to the repository root).
 * @param {{ outdir?: string }} [options]
 * @returns {Promise<{ outdir: string, entrypoints: string[] }>}
 */
export async function build({ outdir = 'dist' } = {}) {
  const dir = resolve(ROOT, outdir);
  const entrypoints = await entrypointNames();
  const stubs = entrypoints.map(
    (name) => `function ${name}(...args) {\n  return ${GLOBAL_NAME}.${name}(...args);\n}`,
  );

  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });
  await esbuild.build({
    ...COMMON,
    format: 'iife',
    globalName: GLOBAL_NAME,
    outfile: join(dir, 'Code.js'),
    banner: { js: '// Generated by scripts/build.js from src/. Do not edit.' },
    footer: { js: ['// Apps Script entrypoints', ...stubs].join('\n') },
  });
  await copyFile(join(ROOT, MANIFEST), join(dir, MANIFEST));
  return { outdir: dir, entrypoints };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const { entrypoints } = await build();
  console.log(`Built dist/Code.js with entrypoints: ${entrypoints.join(', ')}`);
}
